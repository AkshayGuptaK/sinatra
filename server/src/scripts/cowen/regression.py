import argparse
from pathlib import Path
import sys
import numpy as np
import pandas as pd
from sklearn.linear_model import RidgeCV
from sklearn.metrics import mean_squared_error, r2_score
from sklearn.model_selection import KFold, cross_val_predict
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from src.config import config

DATASETS_DIR = config["project_root"] / "datasets"
FEATURES_CSV = DATASETS_DIR / "cowen_features.csv"
MERT_EMBEDDINGS_CSV = DATASETS_DIR / "cowen_MERT-v2-30s_L24_final_embeddings.csv"
CLAP_EMBEDDINGS_CSV = DATASETS_DIR / "cowen_clap-htsat-unfused_final_embeddings.csv"

# Dimensions dropped due to low cross-cultural stability or near-zero signal floor[cite: 1]
DROPPED_EMOTIONS = {
    "entrancing",
    "goose bumps",
    "nauseating/revolting",
    "painful",
}

DEFAULT_STEMS = {
    "mert": "cowen_MERT-v2-30s_L24_final_embeddings",
    "clap": "cowen_clap-htsat-unfused_final_embeddings",
}


def _fit_and_evaluate(
    csv_path_or_df: Path | pd.DataFrame,
    output_path: Path | None = None,
    feature_start_col: str | None = None,
    feature_label: str = "Features",
    feature_cols: list[str] | None = None,
    save_weights: bool = True,
    verbose: bool = True,
    n_splits: int = 10,
    random_state: int = 42,
) -> pd.DataFrame | None:
    if isinstance(csv_path_or_df, Path):
        if not csv_path_or_df.exists():
            print(f"❌ File not found: {csv_path_or_df}")
            return None
        df = pd.read_csv(csv_path_or_df)
        source_name = csv_path_or_df.name
    else:
        df = csv_path_or_df
        source_name = "InMemory DataFrame"

    all_cols = list(df.columns)

    if feature_cols is None:
        if feature_start_col is None:
            # Auto-detect embedding columns generated by MERT or CLAP
            embed_cols = [c for c in all_cols if c.startswith(("mert_", "clap_"))]
            if embed_cols:
                feature_start_col = embed_cols[0]
            elif "vocal_probability" in all_cols:
                feature_start_col = "vocal_probability"
            else:
                print(f"❌ Could not infer feature columns in dataset: {source_name}")
                return None

        if feature_start_col not in all_cols:
            print(f"❌ Column '{feature_start_col}' not found in dataset")
            return None
        split_idx = all_cols.index(feature_start_col)
        raw_mood_cols = all_cols[:split_idx]
        feature_cols = all_cols[split_idx:]
    else:
        raw_mood_cols = [
            c for c in all_cols if c not in feature_cols and not c.startswith("Unnamed")
        ]

    mood_cols = [m for m in raw_mood_cols if m not in DROPPED_EMOTIONS]

    if verbose:
        print(f"\nEvaluating [{feature_label}] from {source_name}")
        print(
            f"Tracks: {len(df)} | Retained Emotions: {len(mood_cols)} (Dropped {len(DROPPED_EMOTIONS)}) | Features: {len(feature_cols)}"
        )

    df_clean = df.dropna(subset=feature_cols + mood_cols).copy()
    X = df_clean[feature_cols].values.astype(np.float32)

    cv = KFold(n_splits=n_splits, shuffle=True, random_state=random_state)
    alphas = np.logspace(-1, 6, 50)

    summary_records = []

    if verbose:
        print("\n" + "=" * 95)
        print(
            f"{'Mood Dimension':<26} | {'R²':<7} | {'RMSE':<7} | Top Positive & Negative Drivers (Std)"
        )
        print("=" * 95)

    for mood in mood_cols:
        y = df_clean[mood].values.astype(np.float32)

        # 1. Leak-free cross-validation via Pipeline
        pipe = make_pipeline(StandardScaler(), RidgeCV(alphas=alphas))
        y_pred = cross_val_predict(pipe, X, y, cv=cv, n_jobs=-1)

        r2 = r2_score(y, y_pred)
        rmse = np.sqrt(mean_squared_error(y, y_pred))

        # 2. Fit on 100% of data to extract parameters
        scaler = StandardScaler()
        X_scaled = scaler.fit_transform(X)

        model = RidgeCV(alphas=alphas)
        model.fit(X_scaled, y)

        scaled_coefs = model.coef_
        scaled_intercept = model.intercept_

        # 3. Fold StandardScaler into raw weights and intercept for raw vector inference
        # y_hat = (x - mu) / sigma @ w_scaled + b_scaled
        #       = x @ (w_scaled / sigma) + (b_scaled - (mu / sigma) @ w_scaled)
        raw_coefs = scaled_coefs / scaler.scale_
        raw_intercept = float(scaled_intercept - np.dot(raw_coefs, scaler.mean_))

        if verbose:
            sorted_indices = np.argsort(scaled_coefs)
            top_neg_idx = sorted_indices[:2]
            top_pos_idx = sorted_indices[-2:][::-1]

            pos_str = ", ".join(
                [f"+{feature_cols[i]} ({scaled_coefs[i]:+.2f})" for i in top_pos_idx]
            )
            neg_str = ", ".join(
                [f"{feature_cols[i]} ({scaled_coefs[i]:+.2f})" for i in top_neg_idx]
            )
            drivers_str = f"{pos_str} | {neg_str}"
            print(f"{mood:<26} | {r2:+.4f} | {rmse:.4f} | {drivers_str}")

        record = {
            "mood": mood,
            "r2": r2,
            "rmse": rmse,
            "intercept": raw_intercept,
        }
        if save_weights and output_path is not None:
            record.update(
                {f"w_{col}": float(coef) for col, coef in zip(feature_cols, raw_coefs)}
            )

        summary_records.append(record)

    results_df = pd.DataFrame(summary_records)

    if save_weights and output_path is not None:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        results_df.to_csv(output_path, index=False)
        if verbose:
            print("=" * 95)
            print(
                f"✅ Saved unscaled-ready weights ({len(results_df)} emotions | Mean R²: {results_df['r2'].mean():.4f}) to {output_path.name}"
            )

    return results_df


def run_mert_regression(
    csv_name: str = DEFAULT_STEMS["mert"],
    output_name: str | None = None,
    verbose: bool = True,
    n_splits: int = 10,
) -> pd.DataFrame | None:
    input_path = DATASETS_DIR / f"{csv_name}.csv"
    out_stem = output_name or f"{csv_name}_regression_weights"
    output_path = DATASETS_DIR / f"{out_stem}.csv"

    return _fit_and_evaluate(
        csv_path_or_df=input_path,
        output_path=output_path,
        feature_start_col=None,
        feature_label=f"MERT [{csv_name}]",
        verbose=verbose,
        n_splits=n_splits,
    )


def run_clap_regression(
    csv_name: str = DEFAULT_STEMS["clap"],
    output_name: str | None = None,
    verbose: bool = True,
    n_splits: int = 10,
) -> pd.DataFrame | None:
    input_path = DATASETS_DIR / f"{csv_name}.csv"
    out_stem = output_name or f"{csv_name}_regression_weights"
    output_path = DATASETS_DIR / f"{out_stem}.csv"

    return _fit_and_evaluate(
        csv_path_or_df=input_path,
        output_path=output_path,
        feature_start_col=None,
        feature_label=f"CLAP [{csv_name}]",
        verbose=verbose,
        n_splits=n_splits,
    )


def run_model_comparison(
    mert_csv: str = DEFAULT_STEMS["mert"],
    clap_csv: str = DEFAULT_STEMS["clap"],
    n_splits: int = 10,
):
    print("\n" + "#" * 95)
    print("🔬 COMPARING MERT vs. LAION-CLAP REGRESSION PROBES")
    print("#" * 95)

    mert_res = run_mert_regression(csv_name=mert_csv, verbose=False, n_splits=n_splits)
    clap_res = run_clap_regression(csv_name=clap_csv, verbose=False, n_splits=n_splits)

    if mert_res is None or clap_res is None:
        print("❌ Could not load one or both regression targets.")
        return

    comp_df = pd.merge(
        mert_res[["mood", "r2", "rmse"]].rename(
            columns={"r2": "mert_r2", "rmse": "mert_rmse"}
        ),
        clap_res[["mood", "r2", "rmse"]].rename(
            columns={"r2": "clap_r2", "rmse": "clap_rmse"}
        ),
        on="mood",
    )
    comp_df["delta_r2"] = comp_df["clap_r2"] - comp_df["mert_r2"]

    print("\n" + "=" * 80)
    print(
        f"{'Mood Dimension':<26} | {'MERT R²':<9} | {'CLAP R²':<9} | {'CLAP - MERT Δ'}"
    )
    print("=" * 80)
    for _, row in comp_df.iterrows():
        print(
            f"{row['mood']:<26} | {row['mert_r2']:+.4f}   | {row['clap_r2']:+.4f}   | {row['delta_r2']:+.4f}"
        )
    print("=" * 80)

    mean_mert = comp_df["mert_r2"].mean()
    mean_clap = comp_df["clap_r2"].mean()
    delta_mean = mean_clap - mean_mert
    print(
        f"Mean R²: MERT = {mean_mert:.4f} | CLAP = {mean_clap:.4f} | Net Δ = {delta_mean:+.4f}\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Cowen Emotion Regression Runner")
    parser.add_argument(
        "mode",
        nargs="?",
        choices=["mert", "clap", "compare", "compare-models"],
        default="mert",
        help="Mode: 'mert', 'clap', or 'compare' (side-by-side comparison)",
    )
    parser.add_argument(
        "--file",
        type=str,
        default=None,
        help="Custom input CSV stem (without .csv). If omitted, picks the mode default.",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Optional custom output filename stem for weights (without .csv)",
    )
    parser.add_argument(
        "--splits",
        type=int,
        default=10,
        help="Number of cross-validation folds (default: 10)",
    )

    args = parser.parse_args()
    mode = args.mode.lower()

    # Resolve filename stem based on selected mode
    target_file = args.file or DEFAULT_STEMS.get(mode)

    if mode == "mert":
        run_mert_regression(
            csv_name=target_file, output_name=args.output, n_splits=args.splits
        )
    elif mode == "clap":
        run_clap_regression(
            csv_name=target_file, output_name=args.output, n_splits=args.splits
        )
    elif mode in ("compare", "compare-models"):
        run_model_comparison(n_splits=args.splits)
    else:
        print(f"Unsupported mode: {mode}")
